def _key(label: str) -> str:
    s = unicodedata.normalize("NFKD", label).encode("ascii", "ignore").decode()
    s = s.lower().replace("&", " and ")
    s = re.sub(r"\bsar china\b", "", s)
    return re.sub(r"[^a-z0-9]+", " ", s).strip()


_BY_NAME: dict[str, str] = {_key(v): k for k, v in NAMES.items()} | ALIASES


def country_code(label: object) -> str | None:
    """ISO alpha-2 code for a country code or name, or ``None`` if ``label`` is not one."""
    if not isinstance(label, str) or not label.strip():
        return None
    s = label.strip()
    if len(s) == 2 and s.isalpha() and s.upper() in NAMES:
        return s.upper()
    return _BY_NAME.get(_key(s))


def country_label(label: object) -> str | None:
    """The ISO code where ``label`` is a known country, else the label itself (``None`` for blanks)."""
    if not isinstance(label, str):
        return None
    s = label.strip()
    if s in ("", "-", "--", "N/A", "n/a", "nan", "None"):
        return None
    return country_code(s) or s
